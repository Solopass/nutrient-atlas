import Dexie, { type EntityTable } from 'dexie'

/** Eating occasions the user picks from. Supplements get their own group in the log. */
export type Meal = 'breakfast' | 'lunch' | 'dinner' | 'snack'
export type LogGroup = Meal | 'supplement'
export type FoodSource = 'ai' | 'custom' | 'usda'

/** A reusable food. Nutrients are totals for one `serving`, keyed by nutrient id. */
export interface Food {
  id: number
  name: string
  serving: string
  grams?: number
  nutrients: Record<string, number>
  source: FoodSource
  favorite: 0 | 1
  useCount: number
  createdAt: number
  lastUsedAt: number
}

/** One logged eating event. Nutrients are snapshotted so later edits to the food don't rewrite history. */
export interface LogEntry {
  id: number
  date: string // local YYYY-MM-DD
  loggedAt: number
  meal: LogGroup
  foodId?: number
  /** Set for supplement doses; drives food-vs-supplement shares and supplement-only upper limits. */
  supplementId?: number
  name: string
  serving: string
  multiplier: number
  nutrients: Record<string, number>
  /** Generated by "Load sample history"; removable in one go. */
  sample?: true
}

/**
 * A supplement defined from its label. Daily supplements are written into the
 * log automatically each day (see lib/supplements.ts), so every other feature
 * treats them like any other entry, and unticking a day just deletes that entry.
 */
export interface Supplement {
  id: number
  name: string
  /** What one dose is, e.g. "1 softgel". */
  dose: string
  /** Per dose, app units, keyed by nutrient id. */
  nutrients: Record<string, number>
  dosesPerDay: number
  schedule: 'daily' | 'asNeeded'
  active: 0 | 1
  startDate: string
  /** Last date the daily dose was auto-logged. */
  lastApplied?: string
  createdAt: number
}

/** A saved meal or recipe: a set of items that can be logged in one tap. */
export interface MealItem {
  name: string
  serving: string
  multiplier: number
  nutrients: Record<string, number>
  foodId?: number
}

export interface SavedMeal {
  id: number
  name: string
  items: MealItem[]
  /** How many portions the items make (a recipe). Logging one portion scales every item by 1/servings. */
  servings: number
  useCount: number
  createdAt: number
  lastUsedAt: number
}

/**
 * A branded food or supplement in your comparison shelf: added from its label,
 * an imported file or an AI reply, then scored and ranked on the Products page.
 * Separate from supplements you take (auto-logged) and foods you log.
 */
export interface Product {
  id: number
  kind: 'supplement' | 'food'
  brand: string
  name: string
  /** One serving as on the label, e.g. "2 capsules" or "1 bar (60 g)". */
  serving: string
  grams?: number
  /** Label calories per serving (foods). */
  kcal?: number
  /** Per serving, app units, keyed by nutrient id. */
  nutrients: Record<string, number>
  /** Ingredient form per nutrient as read from the label, e.g. magnesium → "magnesium glycinate". */
  forms?: Record<string, string>
  servingsPerContainer?: number
  /** Supplements: servings taken per day. */
  servingsPerDay?: number
  /** Price of one container. */
  price?: number
  /** Your rating, 1–5. */
  rating?: number
  notes?: string
  tags?: string[]
  source: 'label' | 'import' | 'ai' | 'manual'
  createdAt: number
  updatedAt: number
}

export interface Setting {
  key: string
  value: unknown
}

export const db = new Dexie('nutrition-app') as Dexie & {
  settings: EntityTable<Setting, 'key'>
  foods: EntityTable<Food, 'id'>
  logs: EntityTable<LogEntry, 'id'>
  supplements: EntityTable<Supplement, 'id'>
  meals: EntityTable<SavedMeal, 'id'>
  products: EntityTable<Product, 'id'>
}

db.version(1).stores({
  foods: '++id, name, lastUsedAt, favorite',
  logs: '++id, date, loggedAt, meal, foodId',
})
db.version(2).stores({ settings: 'key' })
db.version(3).stores({
  logs: '++id, date, loggedAt, meal, foodId, supplementId',
  supplements: '++id, active',
})
db.version(4).stores({ meals: '++id, lastUsedAt' })
db.version(5).stores({ products: '++id, kind, updatedAt' })

export const MEALS: Meal[] = ['breakfast', 'lunch', 'dinner', 'snack']
export const LOG_GROUPS: LogGroup[] = ['supplement', ...MEALS]

export function localDate(d = new Date()) {
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`
}

export function mealForTime(d = new Date()): Meal {
  const h = d.getHours()
  if (h < 11) return 'breakfast'
  if (h < 15) return 'lunch'
  if (h >= 17 && h < 22) return 'dinner'
  return 'snack'
}
